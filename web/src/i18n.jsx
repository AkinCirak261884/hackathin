const LangCtx = createContext(null)

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    try { return localStorage.getItem('gt_lang') || 'en' } catch { return 'en' }
  })
  const change = (l) => {
    setLang(l)
    try { localStorage.setItem('gt_lang', l) } catch {}
    document.documentElement.lang = l
  }
  return <LangCtx.Provider value={{ lang, setLang: change }}>{children}</LangCtx.Provider>
}

export function useT() {
  const { lang, setLang } = useContext(LangCtx)
  const t = (key, ...args) => {
    const v = STRINGS[lang][key] ?? STRINGS.en[key] ?? key
    return typeof v === 'function' ? v(...args) : v
  }
  // pick the right language field from fixture objects: text / text_fr, label / label_fr, title / title_fr
  const tx = (obj, field = 'text') => (obj && ((lang === 'fr' && obj[`${field}_fr`]) || obj[field])) || ''
  const date = (iso) => new Date(iso).toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' })
  return { t, tx, date, lang, setLang }
}
